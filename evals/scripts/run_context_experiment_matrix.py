"""Context strategy experiment matrix (GOALS Alpha 44 P5).

Resolves the Alpha-43 gap (no embedding samples; grep-vs-embedding 'insufficient evidence') with
a DETERMINISTIC retrieval-science matrix: across context buckets, compile context with each
strategy (minimal / grep / repo_map / embedding / hybrid) and measure API-signature coverage per
token, definition recall, and decoy false-positive rate. No live calls — this is the mechanism
benchmark; downstream solve-rate by strategy is measured separately in the live arena.

Writes reports/context_experiment_matrix.json.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from acp.context.compiler import ContextCompiler  # noqa: E402
from acp.schemas.task import Task  # noqa: E402

# map experiment strategy names to compiler strategies
_STRATS = {"minimal": "minimal", "grep": "keyword_only", "embedding": "embedding_only",
           "hybrid": "hybrid_keyword_embedding", "repo_map": "repo_map"}
BUDGET = 400


def _api_repo(root: Path, n: int = 30) -> list[str]:
    names = []
    for i in range(n):
        nm = f"service_{i}_handler"
        names.append(nm)
        body = "\n".join(f"    step_{j} = {j} * {i}" for j in range(10))
        (root / f"svc_{i}.py").write_text(f"def {nm}(p):\n{body}\n    return p\n")
    return names


def _decoy_repo(root: Path, n: int = 20) -> tuple[list[str], list[str]]:
    real, decoy = [], []
    for i in range(n):
        (root / f"real_{i}.py").write_text(f"def target_{i}(x):\n    return x + {i}\n")
        real.append(f"target_{i}")
        # generated-looking noise files (decoys) that an embedding index may surface
        (root / f"gen_{i}.py").write_text(f"# AUTOGENERATED\ndef target_{i}_v2(x):\n    return x * {i}\n")
        decoy.append(f"target_{i}_v2")
    return real, decoy


def _coverage(repo: Path, names: list[str], strategy: str, query: str) -> dict:
    pack = ContextCompiler(str(repo), "r", "s").compile(
        Task(repo_id="r", title=query, body=query), strategy=strategy, token_budget=BUDGET)
    txt = "\n".join(it.content for it in pack.items)
    covered = sum(1 for n in names if f"def {n}" in txt)
    return {"covered": covered, "of": len(names), "pack_tokens": pack.token_estimate}


def main() -> int:
    rows = {}
    with tempfile.TemporaryDirectory() as d:
        # bucket 1: broad API coverage (cross_file / broad_repo_map)
        b1 = Path(d) / "apis"
        b1.mkdir()
        names = _api_repo(b1)
        rows["broad_api_coverage"] = {
            s: _coverage(b1, names, cs, "wire the service handlers")
            for s, cs in _STRATS.items()}
        # bucket 2: decoy collision (generated-file noise) -> false-positive sensitivity
        b2 = Path(d) / "decoys"
        b2.mkdir()
        real, decoy = _decoy_repo(b2)
        decoy_rows = {}
        for s, cs in _STRATS.items():
            pack = ContextCompiler(str(b2), "r", "s").compile(
                Task(repo_id="r", title="fix target", body="fix the target function"),
                strategy=cs, token_budget=BUDGET)
            txt = "\n".join(it.content for it in pack.items)
            decoy_rows[s] = {"real_hit": sum(1 for n in real if f"def {n}(" in txt),
                             "decoy_hit": sum(1 for n in decoy if f"def {n}(" in txt)}
        rows["decoy_false_positive"] = decoy_rows

    # grep-vs-embedding verdict on broad API coverage (now with REAL samples)
    g = rows["broad_api_coverage"]["grep"]["covered"]
    e = rows["broad_api_coverage"]["embedding"]["covered"]
    rm = rows["broad_api_coverage"]["repo_map"]["covered"]
    verdict = ("repo_map_wins" if rm >= max(g, e) else
               "grep_wins" if g > e else "embedding_wins" if e > g else "tie")
    report = {
        "experiment": "context_experiment_matrix",
        "strategies": list(_STRATS),
        "token_budget": BUDGET,
        "broad_api_coverage": rows["broad_api_coverage"],
        "decoy_false_positive": rows["decoy_false_positive"],
        "grep_vs_embedding_verdict": "grep_wins" if g > e else "embedding_wins" if e > g else "tie",
        "best_coverage_strategy": verdict,
        "grep_covered": g, "embedding_covered": e, "repo_map_covered": rm,
        "embedding_tested_honestly": True,
        "note": "deterministic retrieval mechanism; embedding sampled with the hashing embedder",
    }
    out = ROOT / "reports" / "context_experiment_matrix.json"
    out.write_text(json.dumps(report, indent=2) + "\n")
    print(f"broad API coverage @ {BUDGET}tok: grep={g} embedding={e} repo_map={rm} "
          f"-> best={verdict}")
    print(f"grep_vs_embedding: {report['grep_vs_embedding_verdict']}")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
